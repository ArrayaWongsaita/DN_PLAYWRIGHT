import { test, expect } from "@playwright/test";

// ================================================
// บทที่ 31: ควบคุมเวลาด้วย page.clock
// ฝึก: clock.install, pauseAt, runFor, fastForward, setFixedTime
// อ่านเนื้อหาก่อนที่ README.md ในโฟลเดอร์นี้
// timezone ของ browser ตั้งเป็น Asia/Bangkok ไว้แล้วใน playwright.config.ts (sharedUse)
// เราจึงเขียนเวลาแบบมี +07:00 กำกับเสมอ เพื่อให้ผลเหมือนกันทุกเครื่อง
// บทก่อนหน้านี้เลี่ยงการตรวจข้อความที่ขึ้นกับเวลา เพราะเวลาเปลี่ยนตลอด บทนี้เรามีเครื่องมือควบคุมเวลาแล้ว
// ================================================


// ------------------------------------------------
// ตัวอย่างที่ 1: Flash Sale นับถอยหลัง ตั้งเวลาเป็น 23:00 ของวันสุดท้าย (Flash Sale หมดเวลา 2026-12-31 23:59:59)
// ------------------------------------------------
test("หน้าแรก: Flash Sale เหลือเวลา 59 นาที 59 วินาทีเมื่อเวลาเป็น 23:00", async ({ page }) => {
  // install ต้องเรียกก่อน goto เพื่อให้หน้าเว็บใช้นาฬิกาปลอมตั้งแต่เริ่มโหลด
  // เริ่มที่ 22:00 (ก่อนเวลาที่ต้องการ) ปล่อยให้หน้าโหลดตามปกติ
  await page.clock.install({ time: new Date("2026-12-31T22:00:00+07:00") });
  await page.goto("/");

  // หยุดเวลาที่ 23:00:00 พอดี หลังจากนี้เวลาไม่เดินเองแล้ว ค่าบนหน้าจึงนิ่ง ตรวจได้แบบไม่สุ่ม
  await page.clock.pauseAt(new Date("2026-12-31T23:00:00+07:00"));

  // หมดเวลา 23:59:59 ลบ 23:00:00 = เหลือ 59 นาที 59 วินาที
  await expect(page.getByRole("timer", { name: "เวลาที่เหลือ" })).toHaveText("เหลือเวลา 00:59:59");
});


// ------------------------------------------------
// ตัวอย่างที่ 2: คำทักทายตามช่วงเวลา ตั้งเวลาเป็นบ่ายโมงด้วย setFixedTime
// ------------------------------------------------
test("หน้าแรก: เวลา 13:00 ทักทายว่าสวัสดีตอนบ่าย", async ({ page }) => {
  // setFixedTime ทำให้ new Date() / Date.now() คืนค่านี้ตลอด (เหมาะกับหน้าที่อ่านเวลาครั้งเดียว เช่น คำทักทาย)
  // ต้องเรียกก่อน goto เช่นกัน เพราะหน้าอ่านเวลาตอนโหลด
  await page.clock.setFixedTime(new Date("2026-11-12T13:00:00+07:00"));
  await page.goto("/");

  await expect(page.getByTestId("greeting")).toHaveText("สวัสดีตอนบ่าย");
});


