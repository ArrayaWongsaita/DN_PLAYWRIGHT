import { test, expect } from "@playwright/test";

// ================================================
// บทที่ 24: auto-waiting และ actionability (รอเองโดยไม่ต้องสั่ง)
// ฝึก: ปล่อยให้ click รอเอง, timeout ของ expect, waitForURL
// อ่านเนื้อหาก่อนที่ README.md ในโฟลเดอร์นี้
// ห้ามใช้ page.waitForTimeout (หยุดรอเวลาตายตัว) ในบทนี้
// ================================================


// ------------------------------------------------
// ตัวอย่างที่ 1: กดปุ่ม "โหลดข้อมูล" ทันที ทั้งที่ overlay "กำลังเตรียมหน้า..." ยังบังอยู่
// ------------------------------------------------
test("หน้า slow: กดโหลดข้อมูลได้เลย click รอ overlay หายเอง", async ({ page }) => {
  // delay=1000 = ให้ปุ่มโหลดข้อมูลใช้เวลา 1 วินาทีกว่าจะเสร็จ
  await page.goto("/playground/slow?delay=1000");

  // ตอนนี้ overlay "กำลังเตรียมหน้า..." บังหน้าอยู่ราว 1 วินาทีแรก (ปุ่มโดนบัง = ไม่ "receives events")
  // click() จะลองตรวจซ้ำเรื่อยๆ จนปุ่มพร้อม (มองเห็น, นิ่ง, enabled, ไม่โดนบัง) แล้วจึงกดจริง
  // เราไม่ต้องเขียนโค้ดรอ overlay เลย
  await page.getByRole("button", { name: "โหลดข้อมูล" }).click();

  // expect ก็รอเองเหมือนกัน: ลองซ้ำจนข้อความตรงหรือครบ 5 วินาที
  await expect(page.getByRole("status").filter({ hasText: "โหลดข้อมูลเสร็จแล้ว" })).toBeVisible();
});


// ------------------------------------------------
// ตัวอย่างที่ 2: กดปุ่มแล้วหน้าเปลี่ยน URL ใช้ waitForURL รอให้ไปถึงหน้าใหม่
// ------------------------------------------------
test("หน้า slow: กด ไปหน้าถัดไป แล้วรอจนถึงหน้า done", async ({ page }) => {
  await page.goto("/playground/slow");
  await page.getByRole("button", { name: "ไปหน้าถัดไป" }).click();

  // ปุ่มนี้รอ 1 วินาทีก่อนเปลี่ยนหน้า (click จบไปแล้วแต่หน้ายังไม่เปลี่ยน)
  // waitForURL รอจน URL ตรงรูปแบบ "**/playground/slow/done" (** = ขึ้นต้นอะไรก็ได้)
  await page.waitForURL("**/playground/slow/done");

  await expect(page.getByRole("heading", { level: 1, name: "เสร็จแล้ว" })).toBeVisible();
});


// ------------------------------------------------
// ข้อ 1: เหมือนตัวอย่างที่ 1 แต่ delay=1500 กด "โหลดข้อมูล" แล้วตรวจข้อความ "โหลดข้อมูลเสร็จแล้ว"
// แนวทาง: goto("/playground/slow?delay=1500") แล้วทำตามตัวอย่างที่ 1 ได้เลย
// ------------------------------------------------
test("หน้า slow: โหลดข้อมูลด้วย delay 1500", async ({ page }) => {
  // ทำไม: click รอ overlay "กำลังเตรียมหน้า..." หายเอง จึงไม่ต้องรอเองหรือใช้ waitForTimeout
  await page.goto("/playground/slow?delay=1500");
  await page.getByRole("button", { name: "โหลดข้อมูล" }).click();
  // ทำไม: 1.5 วินาทีน้อยกว่า timeout ของ expect (5 วินาที) จึงไม่ต้องเพิ่ม timeout
  await expect(page.getByRole("status").filter({ hasText: "โหลดข้อมูลเสร็จแล้ว" })).toBeVisible();
});


// ------------------------------------------------
// ข้อ 2: ปุ่ม "ส่งฟอร์ม" ตอนแรก disabled (ข้อความ "รอสักครู่...") ประมาณ 1.5 วินาที รอให้พร้อมแล้วกดส่ง
// แนวทาง: หาปุ่มด้วยชื่อ "ส่งฟอร์ม" (ชื่อเปลี่ยนเมื่อพร้อม) expect(...).toBeEnabled() แล้ว click
//        ไม่ต้องตรวจว่าเคย disabled: สถานะ "รอสักครู่..." สั้นและเครื่องช้าอาจพลาด ตรวจแค่สถานะปลายทาง (อ่านหัวข้อ 5 ใน README)
//        ตรวจ role="status" ที่มีข้อความ "ส่งฟอร์มแล้ว"
// ------------------------------------------------
test("หน้า slow: ปุ่มส่งฟอร์มพร้อมใช้งานแล้วกดส่งได้", async ({ page }) => {
  await page.goto("/playground/slow");

  // ทำไม: ไม่ตรวจสถานะชั่วคราว "รอสักครู่..." (disabled ราว 1.5 วินาที) เพราะเครื่องช้าอาจพลาดช่วงนั้นจน test flaky
  // ตรวจเฉพาะสถานะปลายทางที่พลาดไม่ได้: เมื่อพร้อม ชื่อปุ่มเปลี่ยนเป็น "ส่งฟอร์ม" จึงหาด้วยชื่อใหม่
  // toBeEnabled รอจนปุ่มพร้อม (ไม่ต้องหน่วงเวลาเอง)
  const submit = page.getByRole("button", { name: "ส่งฟอร์ม" });
  await expect(submit).toBeEnabled();
  await submit.click();

  await expect(page.getByRole("status").filter({ hasText: "ส่งฟอร์มแล้ว" })).toBeVisible();
});


// ------------------------------------------------
// ข้อ 3: หน้า /products?delay=2000 ตอนแรกแสดง "กำลังโหลดสินค้า..." แล้วรายการสินค้าจึงขึ้น
// แนวทาง: goto("/products?delay=2000")
//        ตรวจข้อความ "พบสินค้า 10 รายการ" (ไม่ต้องรอเอง expect รอให้) แล้วตรวจว่า role="status" "กำลังโหลดสินค้า..." หายไป (toBeHidden)
//        ไม่ต้องตรวจว่า "เคยเห็น" ข้อความกำลังโหลด เพราะเป็นสถานะชั่วคราวที่เครื่องช้าอาจพลาด
// ------------------------------------------------
test("หน้าสินค้าโหลดช้า: ข้อความกำลังโหลดหายไปแล้วเห็นรายการ", async ({ page }) => {
  await page.goto("/products?delay=2000");

  // ทำไม: ตรวจผลปลายทางก่อน expect รอเองได้ (ภายใน 5 วินาที เกิน 2 วินาทีของ delay)
  await expect(page.getByText("พบสินค้า 10 รายการ")).toBeVisible();

  // ทำไม: ไม่ตรวจว่า "เคยเห็น" ข้อความกำลังโหลด (สถานะชั่วคราว เครื่องช้าอาจพลาด)
  // แต่ตรวจว่ามันหายไปแล้ว ซึ่งเป็นสถานะปลายทางที่เป็นจริงเสมอเมื่อรายการขึ้น
  await expect(page.getByRole("status").filter({ hasText: "กำลังโหลดสินค้า..." })).toBeHidden();
});


// ------------------------------------------------
// ข้อ 4: ปุ่มโหลดข้อมูลที่ช้ากว่า timeout ปกติ (5 วินาที): ตั้ง delay=7000 แล้วเพิ่ม timeout เฉพาะ assertion นี้
// แนวทาง: goto("/playground/slow?delay=7000") กด "โหลดข้อมูล"
//        expect(...).toBeVisible({ timeout: 10_000 }) ตรวจข้อความ "โหลดข้อมูลเสร็จแล้ว"
//        ถ้าไม่ใส่ timeout จะ fail ที่ 5 วินาที ลองลบดูแล้วอ่านข้อความ error
// ------------------------------------------------
test("หน้า slow: โหลดข้อมูล 7 วินาที ต้องเพิ่ม timeout ของ expect", async ({ page }) => {
  await page.goto("/playground/slow?delay=7000");
  await page.getByRole("button", { name: "โหลดข้อมูล" }).click();

  // ทำไม: ข้อความขึ้นหลัง 7 วินาที เกิน timeout เริ่มต้นของ expect (5 วินาที) จึงเพิ่ม timeout เฉพาะ assertion นี้
  // (ไม่แก้ทั้งโปรเจกต์ และไม่ใช้ waitForTimeout)
  await expect(page.getByRole("status").filter({ hasText: "โหลดข้อมูลเสร็จแล้ว" })).toBeVisible({ timeout: 10_000 });
});
