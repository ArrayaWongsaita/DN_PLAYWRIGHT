// ------------------------------------------------
// ตัวอย่างที่ 1: กดปุ่ม "โหลดข้อมูล" ทันที ทั้งที่ overlay "กำลังเตรียมหน้า..." ยังบังอยู่
// ------------------------------------------------
test("หน้า slow: กดโหลดข้อมูลได้เลย click รอ overlay หายเอง", async ({ page }) => {
  // delay=1000 = ให้ปุ่มโหลดข้อมูลใช้เวลา 1 วินาทีกว่าจะเสร็จ
  await page.goto("/playground/slow?delay=1000");

  // ตอนนี้ overlay "กำลังเตรียมหน้า..." บังหน้าอยู่ราว 1 วินาทีแรก (ปุ่มโดนบัง = ไม่ "receives events")
  // click() จะลองตรวจซ้ำเรื่อยๆ จนปุ่มพร้อม (มองเห็น, นิ่ง, enabled, ไม่โดนบัง) แล้วจึงกดจริง
  // เราไม่ต้องเขียนโค้ดรอ overlay เลย
  await page.getByRole("button", { name: "โหลดข้อมูล" }).click();

  // expect ก็รอเองเหมือนกัน: ลองซ้ำจนข้อความตรงหรือครบ 5 วินาที
  await expect(page.getByRole("status").filter({ hasText: "โหลดข้อมูลเสร็จแล้ว" })).toBeVisible();
});


// ------------------------------------------------
// ตัวอย่างที่ 2: กดปุ่มแล้วหน้าเปลี่ยน URL ใช้ waitForURL รอให้ไปถึงหน้าใหม่
// ------------------------------------------------
test("หน้า slow: กด ไปหน้าถัดไป แล้วรอจนถึงหน้า done", async ({ page }) => {
  await page.goto("/playground/slow");
  await page.getByRole("button", { name: "ไปหน้าถัดไป" }).click();

  // ปุ่มนี้รอ 1 วินาทีก่อนเปลี่ยนหน้า (click จบไปแล้วแต่หน้ายังไม่เปลี่ยน)
  // waitForURL รอจน URL ตรงรูปแบบ "**/playground/slow/done" (** = ขึ้นต้นอะไรก็ได้)
  await page.waitForURL("**/playground/slow/done");

  await expect(page.getByRole("heading", { level: 1, name: "เสร็จแล้ว" })).toBeVisible();
});


