// ------------------------------------------------
// ตัวอย่างที่ 1: ปุ่ม "เข้าสู่ระบบ" กดไม่ได้จนกว่าจะกรอกครบ (toBeDisabled / toBeEnabled)
// ------------------------------------------------
test("หน้า /login ปุ่มเข้าสู่ระบบ disabled จนกว่าจะกรอกครบทั้งสองช่อง", async ({ page }) => {
  await page.goto("/login");
  // ปุ่มเก็บใส่ตัวแปรไว้ จะได้ใช้ซ้ำโดยไม่ต้องเขียน locator ใหม่
  const loginButton = page.getByRole("button", { name: "เข้าสู่ระบบ" });
  // ตอนเปิดหน้า ช่องยังว่าง ปุ่มต้องกดไม่ได้
  await expect(loginButton).toBeDisabled();

  await page.getByLabel("อีเมล").fill("user@dnshop.test");
  await page.getByLabel("รหัสผ่าน").fill("password123");
  // กรอกครบแล้ว ปุ่มต้องกดได้ (toBeEnabled รอจนปุ่มเปลี่ยนสถานะ ไม่ต้องรอเอง)
  await expect(loginButton).toBeEnabled();
});


// ------------------------------------------------
// ตัวอย่างที่ 2: checkbox ในฟอร์มสมัครสมาชิก (toBeChecked)
// ------------------------------------------------
test("หน้า /register ช่องรับข่าวสารติ๊กไว้ก่อน ส่วนช่องยอมรับเงื่อนไขต้องติ๊กเอง", async ({ page }) => {
  await page.goto("/register");
  // "รับข่าวสารทางอีเมล" ติ๊กไว้ให้แล้วตั้งแต่เปิดหน้า
  await expect(page.getByRole("checkbox", { name: "รับข่าวสารทางอีเมล" })).toBeChecked();

  const terms = page.getByRole("checkbox", { name: "ฉันยอมรับเงื่อนไขการใช้งาน" });
  // ช่องนี้ยังไม่ติ๊ก: toBeChecked({ checked: false }) คือ "ต้องไม่ถูกติ๊ก"
  await expect(terms).toBeChecked({ checked: false });
  await terms.check();
  await expect(terms).toBeChecked();
});


