// ตัวช่วยของบทนี้: เปิด /products กดเพิ่มสินค้าตามชื่อลงตะกร้า แล้วรอข้อความแจ้งสำเร็จ (role="status")
// เขียนให้แล้ว ไม่ต้องแก้ ใช้ได้เลย เช่น await addToCart(page, "เมาส์ไร้สาย")
async function addToCart(page: Page, name: string) {
  await page.goto("/products");
  await page
    .getByRole("listitem")
    .filter({ hasText: name })
    .getByRole("button", { name: "เพิ่มลงตะกร้า" })
    .click();
  await expect(page.getByRole("status").filter({ hasText: `เพิ่ม "${name}" ลงตะกร้าแล้ว` })).toBeVisible();
}

// หลักการของบทนี้: test ที่ AI เขียนต้อง "รันผ่าน" และ "ถูกตาม best practices" ก่อนถึงจะเก็บไว้
// ทุกข้อด้านล่างจึงมีเกณฑ์ตรวจ 4 ข้อเหมือนกัน
//   1) หา element ด้วย getByRole / getByLabel (ไม่ใช่ CSS selector)
//   2) ใช้ expect(locator).toBeXxx() ซึ่งรอเอง ไม่ใช้ waitForTimeout
//   3) ทุก test จบด้วย assertion ที่บอกผลลัพธ์จริง
//   4) test แต่ละตัวทำงานคนเดียวได้ ไม่ต้องพึ่งตัวอื่น


// ------------------------------------------------
// ตัวอย่างที่ 1: ผลสำรวจหน้า /products ด้วย AI: "พิมพ์ค้นหา แล้วเห็นเฉพาะสินค้าที่ตรงคำ"
// ------------------------------------------------
test("หน้า /products ค้นหา เมาส์ แล้วต้องพบสินค้า 1 รายการ", async ({ page }) => {
  await page.goto("/products");

  // AI อ่าน snapshot ของหน้าแล้วเห็น searchbox ชื่อ "ค้นหาสินค้า" กับปุ่ม "ค้นหา" จึงใช้ชื่อเหล่านี้ตรงๆ
  await page.getByRole("searchbox", { name: "ค้นหาสินค้า" }).fill("เมาส์");
  await page.getByRole("button", { name: "ค้นหา" }).click();

  // ผลลัพธ์ที่เห็นในหน้าจริง: ข้อความจำนวน และลิงก์ชื่อสินค้า (assertion รอเองจนกว่าผลจะมา)
  await expect(page.getByText("พบสินค้า 1 รายการ")).toBeVisible();
  await expect(page.getByRole("link", { name: "เมาส์ไร้สาย" })).toBeVisible();
});


