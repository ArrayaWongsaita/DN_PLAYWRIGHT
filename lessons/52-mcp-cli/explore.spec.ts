// ================================================
// บทที่ 52: ให้ AI เปิด browser สำรวจแอป (Playwright MCP และ playwright cli)
// ฝึก: เปลี่ยนสิ่งที่ AI "เห็น" ให้เป็น test ที่ดี: getByRole, assertion แบบ web-first, ไม่มี waitForTimeout
// อ่านเนื้อหาก่อนที่ README.md ในโฟลเดอร์นี้ (prompt สำหรับ copy อยู่ใน prompts.md)
